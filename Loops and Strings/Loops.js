// ==========================================
// 1. LOOPS IN JAVASCRIPT
// ==========================================
// Loops execute a block of code repeatedly as long as a specified condition is true.

// ------------------------------------------
// 1. Traditional `for` loop
// ------------------------------------------
// Best used when the exact number of iterations is known beforehand.
// Syntax: for (initialization; condition; increment/decrement)
console.log("--- 1. Traditional For Loop ---");
for (let i = 1; i <= 5; i++) {
  console.log(`Iteration: ${i}`);
}



